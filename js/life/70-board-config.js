var 
  nn = 90,
  xa = 24,
  _a = 23,
  Hh = 1.42,
  ua = 1.375,
  fs = [];
for (let n = 0; n < xa; n++) fs.push([n, 0, 0, -1]);
for (let n = 1; n < _a; n++) fs.push([xa - 1, n, 1, 0]);
for (let n = xa - 2; n >= 0; n--) fs.push([n, _a - 1, 0, 1]);
for (let n = _a - 2; n >= 1; n--) fs.push([0, n, -1, 0]);
